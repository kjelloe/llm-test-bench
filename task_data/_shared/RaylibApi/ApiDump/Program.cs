static string T(Type t)
{
    if (t.IsByRef) return "ref " + T(t.GetElementType());
    if (t.IsPointer) return T(t.GetElementType()) + "*";
    if (t.IsGenericType) return t.Name.Split('`')[0] + "<" + string.Join(", ", t.GetGenericArguments().Select(T)) + ">";
    return t.FullName switch
    {
        "System.Void" => "void", "System.Int32" => "int", "System.UInt32" => "uint", "System.Single" => "float",
        "System.Double" => "double", "System.Boolean" => "bool", "System.Byte" => "byte", "System.String" => "string",
        "System.SByte" => "sbyte", "System.Int64" => "long", "System.UInt16" => "ushort", "System.Int16" => "short",
        "System.Object" => "object", "System.Char" => "char", _ => t.Name,
    };
}
// A pointer overload next to a ref one is the same call; list the ref form only.
static bool HasPointer(MethodInfo m) => m.GetParameters().Any(p => p.ParameterType.IsPointer);
static string Sig(MethodInfo m) =>
    $"  {T(m.ReturnType)} {m.Name}({string.Join(", ", m.GetParameters().Select(p => $"{T(p.ParameterType)} {p.Name}"))})";
void Methods(Type t, Func<MethodInfo, bool> keep)
{
    var lines = t.GetMethods(BindingFlags.Public | BindingFlags.Static | BindingFlags.DeclaredOnly)
        .Where(m => !m.IsSpecialName && keep(m))
        .Where(m => !HasPointer(m) || !t.GetMethods(BindingFlags.Public | BindingFlags.Static).Any(o => o != m && o.Name == m.Name && !HasPointer(o)))
        .Select(Sig).Distinct().OrderBy(s => s, StringComparer.Ordinal);
    foreach (var l in lines) Console.WriteLine(l);
}
void Enum(Type t)
{
    Console.WriteLine($"enum {t.Name} : {T(System.Enum.GetUnderlyingType(t))}");
    foreach (var n in System.Enum.GetNames(t)) Console.WriteLine($"  {n} = {Convert.ToInt64(System.Enum.Parse(t, n))}");
}
void Struct(Type t)
{
    Console.WriteLine($"struct {t.Name}");
    foreach (var f in t.GetFields(BindingFlags.Public | BindingFlags.Instance)) Console.WriteLine($"  {T(f.FieldType)} {f.Name}");
    foreach (var p in t.GetProperties(BindingFlags.Public | BindingFlags.Instance)) Console.WriteLine($"  {T(p.PropertyType)} {p.Name} {{ get; }}");
    foreach (var c in t.GetConstructors()) Console.WriteLine($"  {t.Name}({string.Join(", ", c.GetParameters().Select(p => $"{T(p.ParameterType)} {p.Name}"))})");
    var statics = t.GetFields(BindingFlags.Public | BindingFlags.Static).Select(f => f.Name).ToArray();
    if (statics.Length > 0) Console.WriteLine($"  static readonly {t.Name}: {string.Join(", ", statics)}");
}
